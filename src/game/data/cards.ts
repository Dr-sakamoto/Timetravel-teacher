import type { Ability, Category, EraId, Rarity, RoleId, StatKey, Stats, Tag } from '../types';

/** 歴史カード（各時代のカードプール）。1枚につき1人しか存在せず、早い者勝ち */
export interface CardDef {
  id: string;
  name: string;
  title: string;
  era: EraId;
  rarity: Rarity;
  icon: string;
  stats: Stats;
  tags: Tag[];
  ability?: Ability;
  flavor: string;
}

type S5 = [number, number, number, number, number];
const st = ([pe, study, fight, art, charm]: S5): Stats => ({ pe, study, fight, art, charm });
const aura = (stat: StatKey, amount: number): Ability => ({ kind: 'aura', stat, amount });
const boost = (category: Category, amount: number): Ability => ({ kind: 'boost', category, amount });
const roleB = (role: RoleId, mult: number): Ability => ({ kind: 'roleBonus', role, mult });
const income = (amount: number): Ability => ({ kind: 'income', amount });
const guard = (ratio: number): Ability => ({ kind: 'guard', ratio });

function era(
  eraId: EraId,
  list: [string, string, string, Rarity, string, S5, Tag[], Ability | undefined, string][],
): CardDef[] {
  return list.map(([id, name, title, rarity, icon, s, tags, ability, flavor]) => ({
    id,
    name,
    title,
    era: eraId,
    rarity,
    icon,
    stats: st(s),
    tags,
    ability,
    flavor,
  }));
}

