import type { Attr, EraId, Rarity, Tag } from '../types';

/** 歴史カード（各時代のカードプール）。1枚につき1人しか存在せず、早い者勝ち */
export interface CardDef {
  id: string;
  name: string;
  title: string;
  era: EraId;
  rarity: Rarity;
  icon: string;
  /** 属性アイコン（同じアイコンが重なるほど強い。カードに印刷するのは1枚あたり最大5個（イベントで6個まで増える）） */
  attrs: Attr[];
  tags: Tag[];
  flavor: string;
}

/** 属性の略記：s=📚勉強 p=🏃運動 a=🎨芸術 c=👑人望 f=👊喧嘩 */
const ATTR_CODE: Record<string, Attr> = { s: 'study', p: 'sports', a: 'art', c: 'charm', f: 'fight' };
export function parseAttrs(code: string): Attr[] {
  return code.replace('=', '').split('').map((ch) => ATTR_CODE[ch]);
}

/**
 * レア度と強さ（power 1〜10）から、カードに印刷するアイコンを決める。強い子ほど同じアイコンが重なる。
 * N=1〜2個、R=2〜3個、SR=3〜4個、SSR=4〜5個。足りない分は得意な属性（先頭）を重ねる。
 */
export function toIcons(code: string, rarity: Rarity, power: number): Attr[] {
  // 先頭が「=」なら個数も含めてそのまま印刷する（恐竜・番長・不良など）
  if (code.startsWith('=')) return parseAttrs(code);
  const base = parseAttrs(code);
  const target =
    rarity === 'N' ? (power >= 5 ? 2 : Math.min(2, base.length))
    : rarity === 'R' ? (power >= 8 ? 3 : 2)
    : rarity === 'SR' ? (power >= 9 ? 4 : 3)
    : power >= 10 ? 5 : 4;
  const out = base.slice(0, target);
  // 👊はヤンキーの印なので削らない
  if (base.includes('fight') && !out.includes('fight')) out[out.length - 1] = 'fight';
  for (let i = 0; out.length < target; i++) out.push(base[i % base.length]);
  return out.sort((x, y) => base.indexOf(x) - base.indexOf(y));
}

type Row = [id: string, name: string, title: string, rarity: Rarity, icon: string, power: number, attrs: string, tags: Tag[], flavor: string];

function era(eraId: EraId, list: Row[]): CardDef[] {
  return list.map(([id, name, title, rarity, icon, power, attrs, tags, flavor]) => ({
    id,
    name,
    title,
    era: eraId,
    rarity,
    icon,
    attrs: toIcons(attrs, rarity, power),
    tags,
    flavor,
  }));
}

